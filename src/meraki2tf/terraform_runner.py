#: Terraform's human plan summary, e.g.
#: ``Plan: 875 to import, 0 to add, 2 to change, 0 to destroy.``
#: Column-anchored: the plan *diff body* renders Meraki-controlled
#: attribute values (rule comments, SSID names) indented or inside
#: heredoc blocks, so only terraform's own summary line — which the
#: parser must never let a crafted value like ``Plan: 0 to add, …``
#: impersonate — starts at column 0.
_PLAN_SUMMARY_RE = re.compile(
    r"^Plan: (?:(?P<imports>\d+) to import, )?(?P<add>\d+) to add, "
    r"(?P<change>\d+) to change, (?P<destroy>\d+) to destroy",
    re.MULTILINE,
)

#: Terraform prints this instead of a ``Plan:`` summary line when the
#: state already matches the configuration exactly (nothing left to
#: import, add, change, or destroy). Column-anchored like the summary.
_PLAN_NO_CHANGES_RE = re.compile(
    r"^No changes\. Your infrastructure matches the configuration\.",
    re.MULTILINE,
)

#: Top-level resource block opener in terraform-generated configuration.
_RESOURCE_BLOCK_RE = re.compile(r'^resource\s+"(?P<type>[^"]+)"\s+"(?P<name>[^"]+)"\s*\{')


def _block_body_end(lines: list[str], index: int) -> tuple[int, bool]:
    """(index of the block's closing column-0 ``}`` line, closer-found).

    ``index`` points at the first line after the block opener. A
    column-0 ``}`` inside a heredoc string body (terraform's generator
    emits heredocs for webhook payloadTemplate bodies and other JSON
    blobs) is string content, not the block closer, and honoring it
    would truncate the block; the heredoc-opener scan is end-anchored
    and quote-aware (see :func:`heredoc_delimiter`) so a ``<<TAG`` inside
    a quoted attribute value can never open a phantom heredoc that runs
    the scan off the end of the block.

    Returns ``(len(lines), False)`` for an unterminated block (no
    column-0 ``}`` before EOF — a corrupted baseline or a runaway
    heredoc) so callers can **fail closed** instead of silently
    truncating to EOF. This mirrors ``plan_reconciler._block_span``,
    which returns ``None`` in the same case.
    """
    delimiter: str | None = None
    while index < len(lines):
        line = lines[index]
        if delimiter is None and line.startswith("}"):
            return index, True
        if delimiter is not None:
            if line.strip() == delimiter:
                delimiter = None
        else:
            delimiter = heredoc_delimiter(line)
        index += 1
    return index, False


def _split_resource_blocks(text: str) -> tuple[str, dict[str, str]]:
    """(preamble, address → block text) for terraform-generated config.

    Blocks are hclfmt-shaped: the opener at column 0, the closing ``}``
    at column 0, and each block's ``# __generated__ …`` header comment
    travels with it. Anything outside a resource block (rare — the
    baseline is purely generated) is preserved verbatim as preamble.
    Every returned chunk ends with exactly one trailing newline so the
    caller can join blocks with a single blank separator line.
    """
    lines = text.splitlines(keepends=True)
    preamble: list[str] = []
    blocks: dict[str, str] = {}
    pending: list[str] = []  # header comments owned by the next block
    index = 0
    while index < len(lines):
        line = lines[index]
        match = _RESOURCE_BLOCK_RE.match(line)
        if match is None:
            if line.lstrip().startswith("#"):
                pending.append(line)
            else:
                if line.strip():
                    preamble.extend(pending)
                    preamble.append(line)
                pending.clear()
            index += 1
            continue
        chunk = list(pending)
        pending.clear()
        chunk.append(line)
        if line.rstrip().endswith("{"):  # multi-line block
            index += 1
            body_end, _ = _block_body_end(lines, index)
            chunk.extend(lines[index:body_end])
            index = body_end
            if index < len(lines):
                chunk.append(lines[index])
        index += 1
        body = "".join(chunk)
        blocks[f"{match['type']}.{match['name']}"] = body.rstrip("\n") + "\n"
    preamble.extend(pending)
    joined = "".join(preamble)
    return (joined.rstrip("\n") + "\n" if joined.strip() else ""), blocks


def _assert_no_merged_blocks(blocks: dict[str, str]) -> None:
    """Raise if any parsed block body holds a second column-0 resource
    opener.

    Two openers in one block is the fingerprint of a mis-parse — a
    runaway heredoc/closer scan folding two adjacent blocks into one.
    Writing it out yields a duplicate/nested definition that fails
    ``terraform validate`` and wedges every later unattended run, so
    fail closed rather than absorb a corrupt baseline. With the
    end-anchored, quote-aware opener scan this should be unreachable in
    practice; it is belt-and-suspenders against any future regression.
    """
    for address, body in blocks.items():
        openers = sum(
            1 for line in body.splitlines() if _RESOURCE_BLOCK_RE.match(line)
        )
        if openers > 1:
            raise TerraformError(
                f"Refusing to absorb generated configuration: the parsed "
                f"block for {address} contains {openers} resource openers, "
                f"indicating a corrupted or mis-parsed {GENERATED_CONFIG_FILENAME}. "
                "Investigate the workspace before rerunning."
            )


class TerraformError(RuntimeError):
    """A terraform invocation failed; message carries the CLI diagnostics."""


class TerraformNotFoundError(TerraformError):
    """The terraform executable could not be launched because it does not exist."""


#: Oldest Terraform release the generated kit can run on: ``import``
#: blocks — the mechanism every DR kit rides on — shipped in 1.5.0.
#: Enforced twice, per belt-and-suspenders: the generated ``terraform``
#: block pins ``required_version`` for anyone running the kit by hand,
#: and :func:`ensure_supported_terraform` probes the binary up front so
#: a scheduled run fails in seconds, not after a multi-hour discovery.
MINIMUM_TERRAFORM_VERSION = (1, 5, 0)

#: The version line of plain ``terraform version`` output
#: (``Terraform v1.7.5``); prerelease/metadata suffixes are ignored.
_TERRAFORM_VERSION_RE = re.compile(r"Terraform v(\d+\.\d+(?:\.\d+)?)")


def terraform_not_found_error(executable: str) -> TerraformNotFoundError:
    """The single actionable diagnostic for a missing terraform binary.

    Shared by the subprocess runner and the preflight probe so the
    operator reads the same remedy no matter which path noticed first.
    """
    return TerraformNotFoundError(
        f"terraform executable {executable!r} was not found. "
        "Install Terraform (https://developer.hashicorp.com/terraform/install) "
        "and ensure it is on PATH, or pass --terraform-bin with the full "
        "path to the binary."
    )


def parse_terraform_version(output: str) -> str | None:
    """The version string carried by ``terraform version`` output.

    Handles both forms robustly: the machine-readable ``-json`` document
    (``{"terraform_version": "1.7.5", …}``) and the human-readable
    ``Terraform v1.7.5`` banner. Returns ``None`` when neither shape is
    recognizable (a wrapper script, a truncated pipe) — callers decide
    whether that is fatal.
    """
    text = output.strip()
    if text.startswith("{"):
        try:
            document = json.loads(text)
        except json.JSONDecodeError:
            document = None
        if isinstance(document, dict):
            value = str(document.get("terraform_version") or "").strip()
            if value:
                return value
    match = _TERRAFORM_VERSION_RE.search(output)
    return match.group(1) if match else None


def probe_terraform_version(executable: str) -> str | None:
    """Launch ``<executable> version`` and parse the reported version.

    Raises :class:`TerraformNotFoundError` (the same actionable message
    the runner itself produces) when the binary cannot be launched at
    all; returns ``None`` when it ran but its output carried no
    recognizable version.
    """
    try:
        completed = subprocess.run(
            (executable, "version"),
            capture_output=True,
            text=True,
            check=False,
        )
    except FileNotFoundError as exc:
        raise terraform_not_found_error(executable) from exc
    except OSError as exc:
        # Present but unlaunchable (permission denied, a directory, …):
        # just as absent for every purpose the probe serves.
        raise TerraformNotFoundError(
            f"terraform executable {executable!r} could not be launched: "
            f"{exc}"
        ) from exc
    return parse_terraform_version(completed.stdout)


def version_tuple(version: str) -> tuple[int, ...]:
    """Leading numeric components of a version string, for comparison."""
    return tuple(int(part) for part in re.findall(r"\d+", version)[:3])


def ensure_supported_terraform(executable: str) -> str | None:
    """Fail fast when the terraform binary is missing or too old.

    Called before discovery starts so a multi-hour sweep is never spent
    on a run that cannot plan. Raises :class:`TerraformNotFoundError`
    for a missing binary and :class:`TerraformError` for a parsed
    version below :data:`MINIMUM_TERRAFORM_VERSION`. An unparseable
    version only warns (a wrapper emitting nonstandard output must not
    block a run the generated ``required_version`` constraint will still
    gate correctly) — the parsed version, when known, is returned.
    """
    version = probe_terraform_version(executable)
    if version is None:
        logger.warning(
            "Could not parse a version from %r 'version' output; "
            "continuing — note that meraki2tf requires Terraform >= "
            "%s (the generated kit enforces it via required_version).",
            executable,
            ".".join(str(part) for part in MINIMUM_TERRAFORM_VERSION),
        )
        return None
    if version_tuple(version) < MINIMUM_TERRAFORM_VERSION:
        raise TerraformError(
            f"terraform {version} is too old for meraki2tf: the "
            "generated kit uses `import` blocks, which require "
            "Terraform >= 1.5.0. Upgrade terraform or point "
            "--terraform-bin at a newer binary."
        )
    logger.debug("terraform %s found at %r.", version, executable)
    return version


class ImportGuardViolation(TerraformError):
    """The sync-mode guard refused to apply a plan that is not import-only.

    Raised *before* anything is applied. Carries the offending plan
    output so the orchestrator can abort with a drift alert instead of
    materializing a mutation.
    """

    def __init__(self, message: str, plan_output: str = "") -> None:
        super().__init__(message)
        self.plan_output = plan_output


def _attr_pairs(
    kind: str, mapping: dict[str, tuple[str, ...]]
) -> set[tuple[str, str, str]]:
    """(kind, address, attribute) triples for progress comparison.

    Progress is tracked per attribute, not per address: a second
    reconciliation pass that touches a *new* attribute of an
    already-edited resource is progress; re-proposing an
    already-applied edit is not.
    """
    return {
        (kind, address, attr)
        for address, attrs in mapping.items()
        for attr in attrs
    }


def _merge_attr_map(
    into: dict[str, tuple[str, ...]], new: dict[str, tuple[str, ...]]
) -> None:
    """Merge attribute tuples per address (sorted, deduplicated)."""
    for address, attrs in new.items():
        into[address] = tuple(sorted({*into.get(address, ()), *attrs}))


@dataclass(frozen=True)
class PlanCounts:
    """Change counts parsed from a terraform plan summary line."""

    imports: int
    add: int
    change: int
    destroy: int

    @property
    def has_real_changes(self) -> bool:
        """True when the plan proposes mutations, not just imports."""
        return (self.add + self.change + self.destroy) > 0


@dataclass(frozen=True)
class TerraformCommandResult:
    """Captured outcome of one terraform subprocess invocation."""

    command: tuple[str, ...]
    returncode: int
    stdout: str
    stderr: str

    @property
    def has_changes(self) -> bool:
        """True for ``plan -detailed-exitcode`` runs that found a delta."""
        return self.returncode == _PLAN_CHANGES_PRESENT

    @property
    def plan_counts(self) -> PlanCounts | None:
        """Parsed plan summary counts, or None when no summary is present.

        Lets the orchestrator report exactly how much of the snapshot is
        still pending aggregation into state versus real change pressure.
        A converged plan prints no ``Plan:`` line at all, only the
        no-changes sentence — that is a definitive zero on every count,
        not an unknown, so idempotent reruns report "0 pending" instead
        of "pending imports unknown".
        """
        match = None
        for match in _PLAN_SUMMARY_RE.finditer(self.stdout):
            pass  # the real summary is terraform's LAST column-0 line
        if match is None:
            if _PLAN_NO_CHANGES_RE.search(self.stdout):
                return PlanCounts(imports=0, add=0, change=0, destroy=0)
            return None
        return PlanCounts(
            imports=int(match.group("imports") or 0),
            add=int(match.group("add")),
            change=int(match.group("change")),
            destroy=int(match.group("destroy")),
        )

    @property
    def has_drift(self) -> bool:
        """True when the plan proposes real changes (add/change/destroy).

        Pending ``import`` blocks are not drift — a plan that only
        imports means discovery found resources the state does not track
        yet, which is the tool's normal snapshot-growing behavior. Falls
        back to the ``-detailed-exitcode`` contract when no summary line
        can be parsed, so an unrecognized plan errs toward alerting.
        """
        counts = self.plan_counts
        if counts is None:
            return self.returncode == _PLAN_CHANGES_PRESENT
        return counts.has_real_changes


@dataclass(frozen=True)
class ReconciledPlanResult:
    """A generation plan plus everything reconciliation did to converge it.

    Exposes the same read surface as :class:`TerraformCommandResult`
    (``has_changes``/``has_drift``/``plan_counts``/``stdout``), so plan
    consumers are agnostic to whether reconciliation ran.
    """

    result: TerraformCommandResult
    #: Resources dropped from the kit because the provider's own
    #: validators reject the configuration terraform generated for
    #: them: address → operator-facing reason. These must be reported
    #: as unsupported (Cardinal Rule 2).
    dropped: dict[str, str]
    #: Secret attributes now excluded from management per resource —
    #: the DR kit cannot carry them; restore manually after a rebuild.
    ignored_secrets: dict[str, tuple[str, ...]]
    #: Attributes rewritten/injected to match state byte-for-byte.
    normalized: dict[str, tuple[str, ...]]

    @property
    def has_changes(self) -> bool:
        return self.result.has_changes

    @property
    def plan_counts(self) -> PlanCounts | None:
        return self.result.plan_counts

    @property
    def has_drift(self) -> bool:
        return self.result.has_drift

    @property
    def stdout(self) -> str:
        return self.result.stdout

    def merged_with_earlier(self, earlier: "ReconciledPlanResult") -> (
        "ReconciledPlanResult"
    ):
        """This plan's outcome, keeping remediations an earlier pass in
        the same run already applied (their diffs are suppressed now,
        so this pass alone would under-report them)."""
        return ReconciledPlanResult(
            result=self.result,
            dropped={**earlier.dropped, **self.dropped},
            ignored_secrets={**earlier.ignored_secrets, **self.ignored_secrets},
            normalized={**earlier.normalized, **self.normalized},
        )


class TerraformRunner:
    """Drives the local ``terraform`` binary inside a managed workspace."""

    def __init__(
        self,
        workdir: Path,
        executable: str = "terraform",
        state_path: Path | None = None,
        backend: BackendConfig | None = None,
    ) -> None:
        self._workdir = workdir
        self._executable = executable
        self._backend = backend if backend is not None else BackendConfig()
        self._default_state = state_path is None
        self._state_path = (
            state_path if state_path is not None else workdir / DEFAULT_STATE_FILENAME
        ).resolve()
        #: terraform init is run at most once per runner; the cached
        #: result is returned on subsequent calls so a remote state read
        #: can self-initialize without re-initializing the backend later.
        self._init_result: TerraformCommandResult | None = None
        #: Run-private snapshot of the rebuild plan, taken at preview
        #: time so ``rebuild_apply`` executes exactly the document the
        #: operator confirmed — never the fixed-name file a concurrent
        #: run may have rewritten between preview and apply.
        self._rebuild_plan_snapshot: Path | None = None
        #: Optional fallback that resolves a Duplicate Set Element
        #: literal to resource addresses from the discovered payloads.
        #: Needed because a duplicate that breaks the provider's own
        #: Read fails before terraform generates any configuration, so
        #: the literal never appears in a config file for the
        #: text-scan to find (see plan loop).
        self._duplicate_value_locator: (
            Callable[[tuple[str, ...]], dict[str, str]] | None
        ) = None
        if (
            not self._backend.is_remote
            and self._state_path == (workdir / LEGACY_STATE_FILENAME).resolve()
        ):
            raise TerraformError(
                f"--state-file must not be named {LEGACY_STATE_FILENAME} "
                "inside the workspace directory: terraform init treats "
                "that exact file as legacy state and empties it during "
                "backend initialization. Choose another name or location "
                f"(default: {DEFAULT_STATE_FILENAME} in the workdir)."
            )

    def set_duplicate_value_locator(
        self, locator: Callable[[tuple[str, ...]], dict[str, str]]
    ) -> None:
        """Install the payload-side duplicate resolver (orchestrator
        provides it once the discovery graph and capture report exist)."""
        self._duplicate_value_locator = locator

    @property
    def workdir(self) -> Path:
        return self._workdir

    @property
    def state_path(self) -> Path:
        return self._state_path

    def prepare_workspace(self) -> Path:
        """Create the execution directory and anchor provider + state backend."""
        # Owner-only container: the kit is secret-free by contract, but
        # it still describes the whole org (firewall rules, VLANs,
        # admins) and the directory holds the 0600 state/plan files —
        # other local users have no business listing it. Only newly
        # created directories get the mode; an operator's existing
        # workdir keeps whatever they chose for it.
        self._workdir.mkdir(mode=0o700, parents=True, exist_ok=True)
        provider_file = self._workdir / PROVIDER_FILENAME
        atomic_write_text(
            provider_file,
            _PROVIDER_TF_TEMPLATE.format(backend_block=self._backend_block()),
        )
        if self._backend.is_remote:
            logger.info(
                "Terraform state lives in the %s backend; at-rest protection "
                "(encryption, access control) is the backend's responsibility, "
                "not local file permissions.",
                self._backend.backend.value,
            )
            logger.debug("Workspace prepared at %s", self._workdir)
            return provider_file
        self._state_path.parent.mkdir(parents=True, exist_ok=True)
        self._adopt_legacy_state()
        if self._state_path.exists():
            self._restrict_state_permissions()
            logger.info("Reusing existing Terraform state at %s.", self._state_path)
        else:
            logger.info(
                "No Terraform state at %s; each run regenerates the full "
                "import snapshot (state is only written when you apply, "
                "e.g. via --rebuild --confirm).",
                self._state_path,
            )
        logger.debug("Workspace prepared at %s", self._workdir)
        return provider_file

    def _backend_block(self) -> str:
        """Render the ``terraform { backend … }`` block for this run."""
        if self._backend.is_remote:
            backend_type = self._backend.backend.value
            return _REMOTE_BACKEND_BLOCK.format(
                backend_type=backend_type,
                credential_hint=_BACKEND_CREDENTIAL_HINTS.get(
                    backend_type, "the backend's own credential variables"
                ),
            )
        return _LOCAL_BACKEND_BLOCK.format(
            state_path=hcl_quote(str(self._state_path))
        )

    def _adopt_legacy_state(self) -> None:
        """Rescue state from the old default location.

        Earlier meraki2tf versions kept the state at
        ``<workdir>/terraform.tfstate`` — the exact filename terraform's
        legacy-state migration destroys (see DEFAULT_STATE_FILENAME).
        When the current default location is empty and the legacy file
        holds a non-empty state, move it so accumulated imports survive
        the upgrade.
        """
        if self._backend.is_remote or not self._default_state:
            return
        legacy = self._workdir / LEGACY_STATE_FILENAME
        if (
            legacy.exists()
            and legacy.stat().st_size > 0
            and not self._state_path.exists()
        ):
            legacy.rename(self._state_path)
            logger.info(
                "Adopted legacy state file %s as %s (terraform init "
                "would destroy state stored under the legacy name).",
                legacy,
                self._state_path,
            )

    def existing_addresses(self) -> frozenset[str]:
        """Resource addresses (``type.name``) already tracked in the state.

        Lets generation skip re-importing resources from prior runs so
        consecutive executions only aggregate the delta. The local
        backend reads the state file directly; a remote backend has no
        local file, so its state is read through terraform itself
        (``show -json``), which requires an initialized workspace.
        """
        if self._backend.is_remote:
            return self._remote_existing_addresses()
        if not self._state_path.exists():
            return frozenset()
        raw = ""
        try:
            raw = self._state_path.read_text(encoding="utf-8")
            if not raw.strip():
                # terraform creates the file before first writing state;
                # an interrupted run leaves this 0-byte placeholder
                # behind. There is nothing in it to lose, so the next
                # (unattended) run must not die on it — anything else
                # unparseable still refuses loudly below.
                logger.warning(
                    "State file %s exists but is empty (interrupted "
                    "earlier run?); treating it as no state.",
                    self._state_path,
                )
                return frozenset()
            document = json.loads(raw)
        except (OSError, json.JSONDecodeError) as exc:
            raise TerraformError(
                f"Existing state file {self._state_path} is unreadable: {exc}"
            ) from exc
        resources = document.get("resources", []) if isinstance(document, dict) else []
        addresses = frozenset(_local_state_addresses(resources))
        logger.info(
            "Existing state tracks %d managed resource(s).", len(addresses)
        )
        return addresses

    def _remote_existing_addresses(self) -> frozenset[str]:
        """Managed resource addresses from a remote backend's state.

        Reads ``terraform show -json`` (state form) rather than a local
        file. An empty/uninitialized remote state has no ``values`` key,
        which yields an empty set — the same signal as a fresh local run.
        """
        self._ensure_init()
        result = self._run("show", "-json")
        try:
            document = json.loads(result.stdout)
        except json.JSONDecodeError as exc:
            raise TerraformError(
                f"terraform show -json produced unparseable state output: {exc}"
            ) from exc
        values = document.get("values") if isinstance(document, dict) else None
        root = values.get("root_module") if isinstance(values, dict) else None
        addresses = frozenset(_show_module_addresses(root))
        logger.info(
            "Existing %s state tracks %d managed resource(s).",
            self._backend.backend.value,
            len(addresses),
        )
        return addresses

    def init(self) -> TerraformCommandResult:
        """Initialize the workspace/backend, at most once per runner.

        Idempotent: the first call runs ``terraform init`` (passing any
        ``-backend-config`` for a remote backend) and caches the result;
        later calls return the cached result so a remote state read can
        self-initialize without re-initializing the backend afterwards.
        ``-reconfigure`` keeps the single init clean when a prior run left
        a different backend/state configuration in the workspace.
        """
        if self._init_result is not None:
            return self._init_result
        args = ["init", "-input=false", "-no-color", "-reconfigure"]
        args.extend(self._backend.init_args())
        self._init_result = self._run(*args)
        return self._init_result

    def _ensure_init(self) -> None:
        """Guarantee the workspace is initialized before a state read."""
        if self._init_result is None:
            self.init()

    def provider_schema_catalog(self) -> "ProviderCatalog":
        """Identity-schema catalog of the provider terraform installed.

        Requires an initialized workspace (:meth:`init`). This is the
        authoritative source for resource matching: the catalog always
        reflects the provider version terraform actually selected.
        """
        from meraki2tf.provider_catalog import ProviderCatalog

        result = self._run("providers", "schema", "-json")
        try:
            document = json.loads(result.stdout)
        except json.JSONDecodeError as exc:
            raise TerraformError(
                f"terraform providers schema produced unparseable output: {exc}"
            ) from exc
        if not isinstance(document, dict):
            raise TerraformError(
                "terraform providers schema produced a non-object document."
            )
        return ProviderCatalog.from_schema_document(document)

    #: Plan invocations one generation call may spend converging: one
    #: for validation drops, one for change remediation, one to verify.
    #: Runaway backstop for the reconciliation loop. Every iteration
    #: must make progress (drop a rejected resource or apply a new
    #: remediation) or the loop breaks on its own; the cap only guards
    #: against pathological plan behavior. Real runs need up to ~4
    #: passes: terraform reports validation errors piecemeal, so two
    #: drop rounds can precede the classify + verify rounds.
    _MAX_PLAN_ATTEMPTS = 10

    def plan_with_generation(
        self,
        save_plan: bool = False,
        reconcile: bool = True,
        targets: Iterable[str] | None = None,
    ) -> ReconciledPlanResult:
        """Speculative check: plan imports, generate missing config, and
        reconcile provider round-trip artifacts (see plan_reconciler).

        Returns with ``has_changes`` reflecting the ``-detailed-exitcode``
        contract (0 = state in sync, 2 = delta present). The plan is
        always saved to the sync plan file *during* planning
        (reconciliation classifies it via ``show -json``; the guarded
        apply verifies the saved plan document), but a saved plan embeds
        the refreshed values of every resource — the same secret
        material that forces the state file to 0600 — so when
        ``save_plan`` is false (no apply will consume it) the file is
        deleted before returning, and it is kept owner-only while it
        exists. Bounded loop: at most ``_MAX_PLAN_ATTEMPTS`` plan
        invocations — remaining changes after that are reported as
        drift, never looped on.

        ``targets`` narrows the plan to the given resource addresses
        (``-target``): after a heal or deferral touches a handful of
        resources, re-verifying them takes minutes instead of re-reading
        the entire kit for hours — the full-kit drift picture was
        already taken by the run's first, untargeted plan.
        """
        try:
            return self._plan_with_generation(
                reconcile=reconcile, targets=targets
            )
        finally:
            if not save_plan:
                (self._workdir / SYNC_PLAN_FILENAME).unlink(missing_ok=True)

    def _plan_with_generation(
        self,
        reconcile: bool = True,
        targets: Iterable[str] | None = None,
    ) -> ReconciledPlanResult:
        dropped: dict[str, str] = {}
        ignored: dict[str, tuple[str, ...]] = {}
        normalized: dict[str, tuple[str, ...]] = {}
        case_repairs_attempted: set[tuple[str, str]] = set()
        target_args = tuple(
            f"-target={address}" for address in targets or ()
        )
        if targets is not None and not target_args:
            # Same stance as plan_targeted: an empty target set would
            # silently degenerate to a full untargeted plan — a multi-
            # hour read window on a busy org. A full plan must be an
            # explicit choice (targets=None), never an accident.
            raise ValueError(
                "plan_with_generation: refusing an empty target set; "
                "pass targets=None for a deliberate full plan."
            )
        args = (
            "plan",
            "-input=false",
            "-no-color",
            "-detailed-exitcode",
            f"-generate-config-out={GENERATED_CONFIG_FILENAME}",
            f"-out={SYNC_PLAN_FILENAME}",
            *target_args,
        )
        allowed = (
            (_PLAN_NO_CHANGES, _PLAN_ERROR, _PLAN_CHANGES_PRESENT)
            if reconcile
            else (_PLAN_NO_CHANGES, _PLAN_CHANGES_PRESENT)
        )
        attempt = 0
        while True:
            attempt += 1
            # terraform refuses to overwrite an existing generation
            # target; leftovers (interrupted or prior iteration) are
            # absorbed first so surgery always edits resources.tf.
            self._absorb_generated_config()
            result = self._run(*args, allowed=allowed)
            self._restrict_plan_file_permissions()
            self._absorb_generated_config()
            final_attempt = attempt >= self._MAX_PLAN_ATTEMPTS
            if result.returncode == _PLAN_ERROR:
                diagnostics = result.stderr or result.stdout
                failures = validation_failures(diagnostics)
                duplicated = duplicate_set_values(diagnostics)
                if duplicated:
                    # terraform names no resource for set-uniqueness
                    # violations; the owner is found in the generated
                    # config — or, when the duplicate broke the
                    # provider's own Read before any config was
                    # generated, in the discovered payloads — and
                    # dropped like any unexpressible asset.
                    located = locate_duplicate_value_resources(
                        (
                            self._workdir / GENERATED_CONFIG_FILENAME,
                            self._workdir / AGGREGATED_CONFIG_FILENAME,
                        ),
                        duplicated,
                    )
                    if self._duplicate_value_locator is not None:
                        for address, reason in self._duplicate_value_locator(
                            duplicated
                        ).items():
                            located.setdefault(address, reason)
                    for address, reason in located.items():
                        failures.setdefault(address, reason)
                if not failures:
                    if plan_throttled(diagnostics) and not final_attempt:
                        logger.warning(
                            "terraform plan failed only because the API "
                            "rate-limited the provider (HTTP 429 after "
                            "all client retries); retrying the plan "
                            "(attempt %d/%d).",
                            attempt + 1, self._MAX_PLAN_ATTEMPTS,
                        )
                        continue
                    raise TerraformError(
                        f"terraform plan failed with exit code "
                        f"{result.returncode}: "
                        f"{result.stderr.strip() or result.stdout.strip()}"
                    )
                if final_attempt:
                    raise TerraformError(
                        f"terraform plan failed with exit code "
                        f"{result.returncode}: "
                        f"{result.stderr.strip() or result.stdout.strip()}"
                    )
                repaired = self._repair_enum_case(
                    failures, case_repairs_attempted
                )
                _merge_attr_map(normalized, repaired)
                remaining = {
                    address: reason
                    for address, reason in failures.items()
                    if address not in repaired
                }
                if remaining:
                    self._drop_unexpressible(remaining)
                    dropped.update(remaining)
                    for address in remaining:
                        # a resource repaired earlier but dropped now is
                        # unsupported, not normalized — report it once.
                        normalized.pop(address, None)
                continue
            if not reconcile or not result.has_drift or final_attempt:
                # import-only plans are healthy snapshot growth; only
                # real add/change/destroy pressure warrants classifying.
                break
            reconciliation = classify_plan(self._show_plan_document())
            if not reconciliation.has_remediations:
                break
            new_ignored, new_normalized = apply_remediations(
                self._workdir,
                reconciliation,
                (GENERATED_CONFIG_FILENAME, AGGREGATED_CONFIG_FILENAME),
            )
            proposed = _attr_pairs("ignore", new_ignored) | _attr_pairs(
                "normalize", new_normalized
            )
            applied = _attr_pairs("ignore", ignored) | _attr_pairs(
                "normalize", normalized
            )
            if not proposed - applied:
                # Every proposed (address, attribute) remediation was
                # applied before yet the diff persists — re-editing
                # would loop forever, so surface it as drift instead.
                logger.warning(
                    "Reconciliation made no further progress; reporting "
                    "the remaining plan changes as drift."
                )
                break
            _merge_attr_map(ignored, new_ignored)
            _merge_attr_map(normalized, new_normalized)
            self._log_reconciliation(reconciliation, new_ignored, new_normalized)
        return ReconciledPlanResult(
            result=result,
            dropped=dropped,
            ignored_secrets=ignored,
            normalized=normalized,
        )

    def _repair_enum_case(
        self,
        failures: dict[str, str],
        attempted: set[tuple[str, str]],
    ) -> dict[str, tuple[str, ...]]:
        """Repair validation failures that are pure enum-case mismatches.

        The provider validator wants e.g. lowercase ``"sun"`` while its
        own Read returned ``"Sun"``; the value is rewritten to the
        provider's casing and pinned with ``ignore_changes`` (state
        keeps the API casing, so the case-only flip-back is phantom —
        see plan_reconciler). ``attempted`` guards the plan loop: a
        repair proposed twice for the same (address, attribute) did not
        take, so it is left to be dropped as unexpressible instead of
        looping forever. Returns the applied repairs for reporting.
        """
        fresh = {
            address: attrs
            for address, attrs in enum_case_repairs(failures).items()
            if any((address, attr) not in attempted for attr in attrs)
        }
        if not fresh:
            return {}
        repaired = apply_enum_case_repairs(
            self._workdir,
            fresh,
            (GENERATED_CONFIG_FILENAME, AGGREGATED_CONFIG_FILENAME),
        )
        attempted.update(
            (address, attr)
            for address, attrs in repaired.items()
            for attr in attrs
        )
        if repaired:
            logger.info(
                "Repaired %d enum case mismatch(es) the provider rejects "
                "in its own read (attribute value recased and pinned via "
                "ignore_changes): %s",
                len(repaired),
                "; ".join(
                    f"{address}: {', '.join(attrs)}"
                    for address, attrs in sorted(repaired.items())
                ),
            )
        return repaired

    def plan_targeted(self, addresses: Iterable[str]) -> TerraformCommandResult:
        """Speculative plan restricted to the given resource addresses.

        The batched state-materialization path uses this to shrink the
        clickops race window from a full-kit multi-hour read pass to a
        few minutes per chunk: import blocks outside the target set are
        ignored by terraform, and the saved plan file is guard-verified
        as import-only by :meth:`apply_import_plan` exactly like a full
        plan. Read-only toward Meraki, like every plan.
        """
        targets = list(addresses)
        if not targets:
            # An empty -target set silently degenerates into a full
            # untargeted multi-hour plan — reopening exactly the race
            # window this method exists to close.
            raise ValueError("plan_targeted requires at least one address.")
        self._absorb_generated_config()
        args = [
            "plan",
            "-input=false",
            "-no-color",
            "-detailed-exitcode",
            f"-generate-config-out={GENERATED_CONFIG_FILENAME}",
            f"-out={SYNC_PLAN_FILENAME}",
        ]
        args.extend(f"-target={address}" for address in targets)
        result = self._run(
            *args,
            allowed=(_PLAN_NO_CHANGES, _PLAN_ERROR, _PLAN_CHANGES_PRESENT),
        )
        if result.returncode == _PLAN_ERROR:
            # An errored plan writes no (or a partial) plan file; drop
            # whatever is on disk so a previous window's saved plan
            # cannot be mistaken for this one downstream.
            (self._workdir / SYNC_PLAN_FILENAME).unlink(missing_ok=True)
        self._restrict_plan_file_permissions()
        self._absorb_generated_config()
        return result

    def defer_resources(self, addresses: frozenset[str]) -> None:
        """Remove kit artifacts for pending imports deferred to the next run.

        Sync mode calls this when a handful of not-yet-imported
        resources keep drifting inside every plan window: pulling them
        from this run's kit lets the import-only remainder apply
        (monotone state growth), and the deferred few — reported in
        alerts — import on the next run. Local file surgery only; state
        and Meraki are untouched.
        """
        logger.warning(
            "Deferring %d racy pending import(s) to the next run: %s",
            len(addresses), ", ".join(sorted(addresses)),
        )
        drop_resource_blocks(
            (
                self._workdir / GENERATED_CONFIG_FILENAME,
                self._workdir / AGGREGATED_CONFIG_FILENAME,
            ),
            set(addresses),
        )
        from meraki2tf.hcl_generator import IMPORTS_FILENAME

        drop_import_blocks(self._workdir / IMPORTS_FILENAME, set(addresses))

    def _drop_unexpressible(self, failures: dict[str, str]) -> None:
        """Remove kit artifacts for resources the provider rejects.

        The provider's validators refused the configuration generated
        from its own Read and no automatic repair applies (see
        ``_repair_enum_case``) — the resource cannot round-trip, so it
        leaves the kit and is reported as unsupported by the
        orchestrator.
        """
        addresses = set(failures)
        logger.warning(
            "Dropping %d resource(s) whose generated configuration the "
            "provider itself rejects: %s",
            len(addresses), ", ".join(sorted(addresses)),
        )
        drop_resource_blocks(
            (
                self._workdir / GENERATED_CONFIG_FILENAME,
                self._workdir / AGGREGATED_CONFIG_FILENAME,
            ),
            addresses,
        )
        from meraki2tf.hcl_generator import IMPORTS_FILENAME

        drop_import_blocks(self._workdir / IMPORTS_FILENAME, addresses)

    @staticmethod
    def _log_reconciliation(
        plan: ReconciliationPlan,
        ignored: dict[str, tuple[str, ...]],
        normalized: dict[str, tuple[str, ...]],
    ) -> None:
        logger.info(
            "Plan reconciliation: %d secret attribute set(s) marked "
            "unmanaged, %d resource(s) normalized to state values%s.",
            len(ignored),
            len(normalized),
            (
                f"; {len(plan.real_changes)} real change(s) left as drift"
                if plan.real_changes
                else ""
            ),
        )

    def plan_resource_actions(self) -> dict[str, tuple[str, ...]]:
        """Per-resource actions from the saved sync plan (``show -json``).

        Maps each planned resource address to its action tuple (e.g.
        ``("update",)`` or ``("no-op",)``), letting sync mode separate
        modified objects (Meraki is truth → baseline regeneration) from
        anything else (abort and alert).
        """
        return _document_resource_actions(self._show_plan_document())

    def _show_plan_document(self, filename: str = SYNC_PLAN_FILENAME) -> Any:
        """A saved plan file rendered as a JSON document.

        Consumers guard the document shape themselves (an unexpected
        non-object tolerantly classifies as "nothing to act on").
        """
        result = self._run("show", "-json", filename)
        try:
            return json.loads(result.stdout)
        except json.JSONDecodeError as exc:
            raise TerraformError(
                f"terraform show -json produced unparseable output: {exc}"
            ) from exc

    #: Plan actions that mutate nothing (imports render as no-op).
    _HARMLESS_PLAN_ACTIONS = frozenset({"no-op", "read"})

    #: Age (mtime) past which a leftover verified plan copy is stale no
    #: matter what: PIDs recycle, so an unrelated live process wearing a
    #: dead run's PID must not keep its secret-bearing copy alive
    #: forever. Generously above any single verify+apply window.
    _STALE_PLAN_COPY_SECONDS = 6 * 60 * 60

    def _exclusive_run_copy(self, source: Path) -> Path:
        """Snapshot a saved plan into a run-private, owner-only copy.

        The copy is created with ``O_EXCL`` so no concurrent run can
        pre-plant or swap the file this run verifies and applies. A run
        killed hard (OOM, power loss) leaves its copy behind: those are
        secret-bearing documents that must not outlive their run, and a
        later run recycling the same PID would trip the exclusive
        create — so copies whose owning process is gone are swept first,
        and a same-PID leftover (the old owner is dead by definition) is
        replaced once. PID liveness alone is spoofable by recycling, so
        copies older than ``_STALE_PLAN_COPY_SECONDS`` are swept
        regardless of whether some unrelated process wears the PID now.
        """
        now = time.time()
        for leftover in self._workdir.glob(f"{source.name}.verified-*"):
            suffix = leftover.name.rsplit("-", 1)[-1]
            stale = suffix.isdigit() and not _process_alive(int(suffix))
            if not stale:
                try:
                    age = now - leftover.stat().st_mtime
                except OSError:
                    # Racing deletion by a concurrent sweep: nothing
                    # left to remove.
                    continue
                stale = age > self._STALE_PLAN_COPY_SECONDS
            if stale:
                leftover.unlink(missing_ok=True)
        target = self._workdir / f"{source.name}.verified-{os.getpid()}"
        plan_bytes = source.read_bytes()
        flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL
        try:
            descriptor = os.open(target, flags, 0o600)
        except FileExistsError:
            target.unlink(missing_ok=True)
            descriptor = os.open(target, flags, 0o600)
        with os.fdopen(descriptor, "wb") as handle:
            handle.write(plan_bytes)
        return target

    def apply_import_plan(self) -> tuple[str, ...]:
        """Guarded sync-mode apply: grow the state, never touch Meraki.

        Belt-and-suspenders contract enforcement — regardless of what
        the caller believes about the plan, this method verifies the
        **saved plan document itself** (``terraform show -json`` on the
        plan file, a local read) immediately before applying that exact
        file: it refuses with :class:`ImportGuardViolation` unless every
        planned action is harmless (no-op/read — imports render as
        no-op). Applying a saved plan executes only the actions recorded
        in it — terraform never recomputes a diff at apply time, and
        refuses the plan wholesale if the state changed underneath.
        Verification and apply both run against a run-private copy of
        the plan file, so a concurrent run rewriting the shared plan
        filename cannot swap in a mutating plan between the two steps.
        Deliberately NOT a fresh re-plan: a full-kit re-plan is a
        multi-hour read window that a busy organization races with new
        clickops edits, starving the apply forever.

        Returns the resource addresses the apply added to the state,
        sorted, so every run reports exactly how the state grew.
        """
        before = self.existing_addresses()
        plan_file = self._workdir / SYNC_PLAN_FILENAME
        if not plan_file.exists():
            raise ImportGuardViolation(
                "Refusing to apply: no saved plan file exists to verify.",
                plan_output="",
            )
        # Verification and execution must be bound to one immutable
        # artifact: a concurrent run sharing the workdir (e.g. an
        # overlapping cron firing) rewrites the fixed plan filename, and
        # terraform only refuses a swapped plan when the state serial
        # moved — a mutating plan made against the same state would
        # apply unverified. Snapshot the plan into a run-private,
        # exclusively created owner-only copy; verify and apply THAT.
        verified_file = self._exclusive_run_copy(plan_file)
        verified_name = verified_file.name
        try:
            try:
                document = self._show_plan_document(verified_name)
            except TerraformError as exc:
                raise ImportGuardViolation(
                    "Refusing to apply: the saved plan could not be "
                    f"verified: {exc}",
                    plan_output="",
                ) from exc
            malformed = _document_malformed_entry_count(document)
            if malformed:
                # The lenient parse below skips entries it cannot read;
                # inside the guard an unreadable entry must refuse, not
                # pass as "no mutation".
                raise ImportGuardViolation(
                    "Refusing to apply: the saved plan document carries "
                    f"{malformed} resource change entry(ies) whose shape "
                    "cannot be verified.",
                    plan_output="",
                )
            actions = _document_resource_actions(document)
            mutations = {
                address: acts
                for address, acts in actions.items()
                if not set(acts) <= self._HARMLESS_PLAN_ACTIONS
            }
            if mutations:
                raise ImportGuardViolation(
                    "Refusing to apply: the saved plan proposes mutations "
                    "(" + ", ".join(
                        f"{address}={'+'.join(acts)}"
                        for address, acts in sorted(mutations.items())
                    ) + "); only 100% import plans may be applied "
                    "unattended.",
                    plan_output="\n".join(
                        f"{address}: {'+'.join(acts)}"
                        for address, acts in sorted(mutations.items())
                    ),
                )
            imports = _document_import_count(document)
            if imports == 0:
                logger.info(
                    "State already aggregates every import; nothing to apply."
                )
                return ()
            logger.info(
                "Import-only plan verified from the saved plan document "
                "(%d import(s), 0 mutations); applying to materialize state.",
                imports,
            )
            self._run("apply", "-input=false", "-no-color", verified_name)
            self._restrict_state_permissions()
        finally:
            verified_file.unlink(missing_ok=True)
            plan_file.unlink(missing_ok=True)
        added = tuple(sorted(self.existing_addresses() - before))
        logger.info("State materialized: %d resource(s) added.", len(added))
        return added

    def remove_resources(self, addresses: Iterable[str]) -> None:
        """Remove resources from the accumulated baseline and the state.

        Local surgery only — Meraki is never touched. Used for the two
        human-sanctioned removal paths: confirmed deletions (the object
        is gone from Meraki) and sync-mode baseline regeneration of
        modified objects (state rm + prune turns them back into import
        candidates, so terraform regenerates their HCL from current
        Meraki truth).
        """
        targets = sorted(set(addresses))
        if not targets:
            return
        self._prune_baseline(targets)
        existing = self.existing_addresses()
        tracked = [address for address in targets if address in existing]
        if tracked:
            # `state rm` writes a full pre-removal state backup (secret
            # material included); route it to a fixed path instead of
            # terraform's timestamped default. The 0o077 subprocess
            # umask (see _run) makes terraform create it owner-only
            # from the first byte.
            backup = self._state_path.with_name(self._state_path.name + ".backup")
            try:
                self._run("state", "rm", "-no-color", f"-backup={backup}", *tracked)
            except TerraformError:
                if backup.exists():
                    # a failed removal may have half-modified the state;
                    # the backup is the recovery copy — keep it, locked
                    # down, and tell the operator where it landed.
                    restrict_to_owner(backup)
                    logger.warning(
                        "terraform state rm failed; the pre-removal state "
                        "backup was kept for manual recovery at %s "
                        "(owner-only).",
                        backup,
                    )
                raise
            # The backup exists only to survive a crash mid-removal.
            # Once the rm succeeded it is a plaintext secret-bearing
            # state copy with no remaining purpose — under a remote
            # backend it would be the only state material on local disk
            # — so it must not persist (contract: only the snapshot and
            # the state itself may carry secrets at rest).
            backup.unlink(missing_ok=True)
            self._restrict_state_permissions()
        untracked = len(targets) - len(tracked)
        logger.info(
            "Removed %d of %d requested resource(s) from the Terraform "
            "state%s.",
            len(tracked),
            len(targets),
            (
                f" ({untracked} already absent, e.g. dropped by an "
                "earlier refresh)"
                if untracked
                else ""
            ),
        )

    def _prune_baseline(self, addresses: Iterable[str]) -> None:
        """Drop the given resources' blocks from the accumulated resources.tf.

        The baseline is terraform-generated (hclfmt formatted), so every
        top-level resource block opens with ``resource "type" "name" {``
        at column 0 and closes with ``}`` at column 0.
        """
        aggregated = self._workdir / AGGREGATED_CONFIG_FILENAME
        if not aggregated.exists():
            return
        remove = set(addresses)
        lines = aggregated.read_text(encoding="utf-8").splitlines(keepends=True)
        kept: list[str] = []
        pruned = 0
        index = 0
        while index < len(lines):
            match = _RESOURCE_BLOCK_RE.match(lines[index])
            if match and f"{match['type']}.{match['name']}" in remove:
                multiline = lines[index].rstrip().endswith("{")
                if multiline:
                    end, terminated = _block_body_end(lines, index + 1)
                    if not terminated:
                        # Fail closed: an unterminated block (no column-0
                        # closer before EOF — a corrupted baseline or a
                        # runaway heredoc) would delete every line to EOF,
                        # silently dropping later resource blocks from the
                        # DR baseline while coverage.json still reports
                        # them imported/pending (Cardinal Rule 2). Keep
                        # the block, warn, and leave the file untouched.
                        logger.warning(
                            "Skipped pruning %s.%s from %s: its block has no "
                            "column-0 closing brace before end of file "
                            "(corrupted baseline or unterminated heredoc); "
                            "pruning would truncate the file and silently "
                            "drop later resource blocks.",
                            match["type"],
                            match["name"],
                            AGGREGATED_CONFIG_FILENAME,
                        )
                        kept.append(lines[index])
                        index += 1
                        continue
                pruned += 1
                # The block's `# __generated__ by Terraform from "<id>"`
                # header travels with it; leaving it behind would stack
                # stale deleted-object locators above the next block.
                while kept and kept[-1].lstrip().startswith("#"):
                    kept.pop()
                if not multiline:  # one-line block
                    index += 1
                else:
                    index = end + 1  # past the closing brace
                while index < len(lines) and not lines[index].strip():
                    index += 1  # the blank separator after the block
                continue
            kept.append(lines[index])
            index += 1
        if pruned:
            # Atomic replace, never in-place rewrite: a torn resources.tf
            # wedges every unattended run after it (matches the absorb
            # path's guarantee below).
            atomic_write_text(aggregated, "".join(kept))
            logger.info(
                "Pruned %d resource block(s) from %s.", pruned, AGGREGATED_CONFIG_FILENAME
            )

    def _absorb_generated_config(self) -> None:
        """Fold freshly generated config into the persistent resources.tf.

        Deleting the generation target instead (the naive fix for
        terraform's refusal to overwrite it) would leave state-tracked
        resources with no configuration, so every subsequent plan would
        propose destroying them — a false drift alert, and a workspace
        that tears the organization down if rebuild-applied. Accumulating
        keeps the workspace a faithful, apply-safe DR kit and lets the
        plan compare tracked resources against their captured baseline.
        """
        generated = self._workdir / GENERATED_CONFIG_FILENAME
        if not generated.exists():
            return
        content = generated.read_text(encoding="utf-8")
        if content.strip():
            aggregated = self._workdir / AGGREGATED_CONFIG_FILENAME
            existing = (
                aggregated.read_text(encoding="utf-8")
                if aggregated.exists()
                else ""
            )
            old_preamble, old_blocks = _split_resource_blocks(existing)
            new_preamble, new_blocks = _split_resource_blocks(content)
            # Defence-in-depth: never write a block that a mis-parse
            # merged two definitions into (would fail validate).
            _assert_no_merged_blocks(new_blocks)
            replayed = (
                bool(new_blocks)
                and all(
                    old_blocks.get(address) == body
                    for address, body in new_blocks.items()
                )
                and (not new_preamble or new_preamble in old_preamble)
            )
            if replayed:
                # A crash between last run's absorb and the unlink below
                # replays this call; absorbing again would be a no-op,
                # so only clean up the leftover generation target.
                logger.info(
                    "Generated configuration already absorbed into %s; "
                    "cleaning up the leftover generation target.",
                    AGGREGATED_CONFIG_FILENAME,
                )
            else:
                # Merge by address (fresh generation wins) and write the
                # blocks in address order: terraform emits them in plan
                # order, which varies run to run and would churn diffs
                # for anyone committing the kit. Atomic replace, never
                # in-place append: a crash mid-append leaves a torn
                # resources.tf that wedges every unattended run after it.
                merged = {**old_blocks, **new_blocks}
                parts = [p for p in (old_preamble, new_preamble) if p.strip()]
                parts.extend(merged[address] for address in sorted(merged))
                atomic_write_text(aggregated, "\n".join(parts))
                logger.info(
                    "Absorbed newly generated configuration into %s.",
                    AGGREGATED_CONFIG_FILENAME,
                )
        generated.unlink()

    def has_config_baseline(self) -> bool:
        """Whether the workspace holds accumulated resource configuration."""
        return (self._workdir / AGGREGATED_CONFIG_FILENAME).exists()

    def ensure_baseline_resettable(
        self, existing_addresses: frozenset[str]
    ) -> None:
        """Raise unless --rebaseline may discard the configuration baseline.

        Refused while the state tracks resources: their configuration
        cannot be regenerated (they are skipped from imports.tf, and
        terraform only generates config for import targets), so deleting
        the baseline would make the plan propose destroying all of them.
        Split out so the orchestrator can refuse before spending a full
        discovery pass on a run that cannot proceed.
        """
        if existing_addresses:
            raise TerraformError(
                "--rebaseline cannot discard the configuration baseline while "
                f"the state file tracks {len(existing_addresses)} resource(s); "
                "their configuration would not be regenerated and the plan "
                "would propose destroying them. Reset or relocate the state "
                "file first."
            )

    def reset_baseline(self, existing_addresses: frozenset[str]) -> None:
        """Discard resources.tf so this run regenerates it from live data."""
        self.ensure_baseline_resettable(existing_addresses)
        aggregated = self._workdir / AGGREGATED_CONFIG_FILENAME
        if aggregated.exists():
            aggregated.unlink()
            logger.info(
                "Baseline reset: %s discarded; this run regenerates the "
                "configuration from currently discovered data.",
                AGGREGATED_CONFIG_FILENAME,
            )

    def plan_preview(self) -> TerraformCommandResult:
        """Read-only preview of what a disaster-recovery apply would do.

        Runs ``terraform plan`` over the artifacts already in the
        workspace (no config generation) and **saves the plan** so the
        ``--rebuild`` action shows exactly what ``--confirm`` will
        execute — the apply consumes this saved file, never a fresh
        unattended re-plan that could differ from what the human saw.
        """
        result = self._run(
            "plan",
            "-input=false",
            "-no-color",
            "-detailed-exitcode",
            f"-out={REBUILD_PLAN_FILENAME}",
            allowed=(_PLAN_NO_CHANGES, _PLAN_CHANGES_PRESENT),
        )
        plan_path = self._workdir / REBUILD_PLAN_FILENAME
        if plan_path.exists():
            restrict_to_owner(plan_path)
            # Bind the eventual apply to this exact document: the fixed
            # filename can be rewritten by a concurrent run between
            # preview and apply, and terraform only refuses a swapped
            # plan when the state serial moved underneath it.
            self._rebuild_plan_snapshot = self._exclusive_run_copy(plan_path)
        return result

    def rebuild_apply(self) -> TerraformCommandResult:
        """Execute ``terraform apply`` for an explicit disaster-recovery rebuild.

        The pipeline never calls this — normal runs are strictly
        read-only toward the Meraki organization. The only caller is the
        human-invoked ``--rebuild --confirm`` CLI action, and what runs
        is the exact plan file :meth:`plan_preview` showed the operator;
        terraform itself refuses the file if the state has changed since.
        """
        snapshot = self._rebuild_plan_snapshot
        if snapshot is None or not snapshot.exists():
            raise TerraformError(
                "No saved rebuild plan to apply; run the preview first "
                "(the --rebuild flow plans before applying)."
            )
        try:
            result = self._run(
                "apply", "-input=false", "-no-color", snapshot.name
            )
        finally:
            # Saved plans embed refreshed sensitive values like the
            # state file; consume-or-delete, never leave one behind.
            snapshot.unlink(missing_ok=True)
            self._rebuild_plan_snapshot = None
            (self._workdir / REBUILD_PLAN_FILENAME).unlink(missing_ok=True)
        self._restrict_state_permissions()
        return result

    def discard_rebuild_plan(self) -> None:
        """Delete the saved rebuild plan (preview-only runs must not
        leave a secret-bearing plan document on disk)."""
        (self._workdir / REBUILD_PLAN_FILENAME).unlink(missing_ok=True)
        if self._rebuild_plan_snapshot is not None:
            self._rebuild_plan_snapshot.unlink(missing_ok=True)
            self._rebuild_plan_snapshot = None

    def discard_saved_plan(self) -> None:
        """Delete the saved sync plan file, if one is lingering.

        The saved plan document embeds refreshed sensitive values
        exactly like the state file; only the snapshot and the state may
        hold secrets at rest, so a plan that will no longer be applied
        must not outlive its run.
        """
        (self._workdir / SYNC_PLAN_FILENAME).unlink(missing_ok=True)

    def _restrict_plan_file_permissions(self) -> None:
        """Owner-only (0600) permissions on the saved plan file.

        A saved plan document embeds the refreshed values of every
        planned resource (SSID PSKs, SNMP community strings, …) exactly
        like the state file; terraform writes it with default
        permissions.
        """
        plan_file = self._workdir / SYNC_PLAN_FILENAME
        if plan_file.exists():
            restrict_to_owner(plan_file)

    def _restrict_state_permissions(self) -> None:
        """Owner-only (0600) permissions on the state file and its backup.

        Terraform state stores every sensitive attribute in plaintext
        (SSID PSKs, SNMP community strings, …); terraform itself writes
        it with default permissions. Remote backends keep no local state
        file — at-rest protection is the backend's job — so this is a
        no-op for them.
        """
        if self._backend.is_remote:
            return
        for path in (
            self._state_path,
            self._state_path.with_name(self._state_path.name + ".backup"),
        ):
            if path.exists():
                restrict_to_owner(path)

    @staticmethod
    def _subprocess_env() -> dict[str, str]:
        """Environment for terraform subprocesses.

        The ``CiscoDevNet/meraki`` provider authenticates via
        ``MERAKI_API_KEY``, while meraki2tf follows the Meraki SDK
        convention of ``MERAKI_DASHBOARD_API_KEY``. Bridge the two so
        the speculative plan and guarded applies can authenticate,
        keeping the credential out of every file the runner writes. An
        explicitly set ``MERAKI_API_KEY`` always wins. Throttle
        resilience defaults (``PROVIDER_THROTTLE_ENV_DEFAULTS``) are
        injected the same way: only when the operator left them unset.
        """
        env = dict(os.environ)
        dashboard_key = env.get(API_KEY_ENV_VAR, "").strip()
        if dashboard_key and not env.get(PROVIDER_API_KEY_ENV_VAR, "").strip():
            env[PROVIDER_API_KEY_ENV_VAR] = dashboard_key
        for var, default in PROVIDER_THROTTLE_ENV_DEFAULTS:
            if not env.get(var, "").strip():
                env[var] = default
        return env

    def _run(
        self, *args: str, allowed: tuple[int, ...] = (0,)
    ) -> TerraformCommandResult:
        command = (self._executable, *args)
        logger.debug("Executing: %s (cwd=%s)", " ".join(command), self._workdir)
        try:
            completed = subprocess.run(
                command,
                cwd=self._workdir,
                capture_output=True,
                text=True,
                check=False,
                env=self._subprocess_env(),
                # Terraform creates the state file, its backups, and
                # saved plan files itself; an 0o077 umask makes them
                # owner-only from the first byte instead of leaving a
                # world-readable window until the post-run chmod.
                # subprocess's own umask parameter, not preexec_fn: a
                # Python-level preexec_fn can deadlock the forked child
                # when other threads (discovery pool) are live. -1 is
                # the "leave unset" sentinel for non-POSIX platforms.
                umask=0o077 if os.name == "posix" else -1,
            )
        except FileNotFoundError as exc:
            raise terraform_not_found_error(self._executable) from exc
        if completed.stdout:
            if "-json" in args:
                # Machine-readable output (plan/state JSON) carries
                # sensitive values in plaintext — never log the body.
                # Human-readable terraform output masks them itself.
                logger.debug(
                    "terraform %s stdout: %d byte(s) of machine-readable "
                    "JSON (body not logged: may carry sensitive values).",
                    args[0], len(completed.stdout),
                )
            else:
                logger.debug(
                    "terraform %s stdout:\n%s", args[0], completed.stdout
                )
        if completed.stderr:
            logger.debug("terraform %s stderr:\n%s", args[0], completed.stderr)
        if completed.returncode not in allowed:
            if "-json" in args:
                # Same rule as the debug log: machine-readable stdout
                # can carry sensitive values, and this message flows
                # into alert payloads — report its size, not its body.
                detail = completed.stderr.strip() or (
                    f"{len(completed.stdout)} byte(s) of machine-readable "
                    "JSON on stdout (not echoed: may carry sensitive "
                    "values)"
                )
            else:
                detail = completed.stderr.strip() or completed.stdout.strip()
            raise TerraformError(
                f"terraform {args[0]} failed with exit code "
                f"{completed.returncode}: {detail}"
            )
        return TerraformCommandResult(
            command=command,
            returncode=completed.returncode,
            stdout=completed.stdout,
            stderr=completed.stderr,
        )


def _process_alive(pid: int) -> bool:
    """Whether a process with this PID currently exists.

    Signal 0 probes without delivering; EPERM means the PID exists but
    belongs to another user, which still counts as alive — its
    run-private plan copy is not ours to sweep.
    """
    try:
        os.kill(pid, 0)
    except ProcessLookupError:
        return False
    except (OverflowError, ValueError):
        # A PID the kernel cannot even represent names no process.
        return False
    except OSError:
        return True
    return True


def _local_state_addresses(resources: Any) -> Iterator[str]:
    """Full managed-instance addresses from a raw local state document.

    Addresses carry the module path and instance keys
    (``module.m.type.name["key"]``) so before/after state comparisons
    and the skip-existing set stay correct when an operator adds a
    module or a counted resource to the workspace. A plain root-module
    resource yields the bare ``type.name`` the generated kit uses —
    identical to what tool-driven comparisons always keyed on.
    """
    for resource in resources if isinstance(resources, list) else ():
        if not (
            isinstance(resource, dict)
            and resource.get("mode") == "managed"
            and resource.get("type")
            and resource.get("name")
        ):
            continue
        base = f"{resource['type']}.{resource['name']}"
        module = resource.get("module")
        if module:
            base = f"{module}.{base}"
        instances = resource.get("instances")
        keys = [
            instance.get("index_key")
            for instance in (instances if isinstance(instances, list) else ())
            if isinstance(instance, dict)
        ]
        if not any(key is not None for key in keys):
            # single-instance resource (or no instance detail): the
            # address has no index part.
            yield base
            continue
        for key in keys:
            # count/for_each instances: [0] / ["key"] — json.dumps
            # renders exactly terraform's index syntax for both.
            yield base if key is None else f"{base}[{json.dumps(key)}]"


def _show_module_addresses(module: Any) -> Iterator[str]:
    """Managed resource addresses from one ``show -json`` module node.

    Descends ``child_modules`` recursively so module-nested resources
    are counted like root ones. Show output carries each instance's
    full address (module path + index key) on the entry itself; the
    ``type.name`` fallback covers only documents without it.
    """
    if not isinstance(module, dict):
        return
    resources = module.get("resources")
    for resource in resources if isinstance(resources, list) else ():
        if not isinstance(resource, dict) or resource.get("mode") != "managed":
            continue
        if resource.get("address"):
            yield str(resource["address"])
        elif resource.get("type") and resource.get("name"):
            yield f"{resource['type']}.{resource['name']}"
    children = module.get("child_modules")
    for child in children if isinstance(children, list) else ():
        yield from _show_module_addresses(child)


def _document_malformed_entry_count(document: Any) -> int:
    """Resource-change entries a shown plan document carries that the
    lenient parser would skip — the guard refuses when any exist. An
    empty actions list is malformed too: it would pass the harmless
    check vacuously, and the guard refuses anything it cannot verify."""
    changes = document.get("resource_changes") if isinstance(document, dict) else None
    return sum(
        1
        for change in changes or ()
        if not isinstance(change, dict)
        or not change.get("address")
        or not isinstance(change.get("change"), dict)
        or not isinstance(change["change"].get("actions"), list)
        or not change["change"]["actions"]
    )


def _document_resource_actions(document: Any) -> dict[str, tuple[str, ...]]:
    """Per-resource action tuples from a shown plan document.

    One address can carry several entries — a deposed object rides
    alongside the current one — so actions are accumulated, never
    overwritten: a deposed ``delete`` must not be shadowed by the
    current object's ``no-op`` inside the apply guard."""
    actions: dict[str, tuple[str, ...]] = {}
    changes = document.get("resource_changes") if isinstance(document, dict) else None
    for change in changes or ():
        if not isinstance(change, dict) or not change.get("address"):
            continue
        change_body = change.get("change")
        raw = change_body.get("actions", ()) if isinstance(change_body, dict) else ()
        address = str(change["address"])
        actions[address] = actions.get(address, ()) + tuple(
            str(action) for action in raw
        )
    return actions


def _document_import_count(document: Any) -> int:
    """How many resources a shown plan document imports (``importing``)."""
    changes = document.get("resource_changes") if isinstance(document, dict) else None
    return sum(
        1
        for change in changes or ()
        if isinstance(change, dict)
        and isinstance(change.get("change"), dict)
        and change["change"].get("importing")
    )
