def test_force_delete_identity_inserts_literal_false(
    tmp_path: Path, recorder: RecordingNotifier
) -> None:
    """Group-policy-style identities import as <scope>,false,<id> so an
    import can never be armed to cascade a delete."""
    spec = {
        "openapi": "3.0.1",
        "paths": {
            "/networks/{networkId}/groupPolicies": {
                "get": {"operationId": "getPolicies", "tags": ["networks"]},
                "post": {"operationId": "createPolicy", "tags": ["networks"]},
            },
            "/networks/{networkId}/groupPolicies/{groupPolicyId}": {
                "get": {"operationId": "getPolicy", "tags": ["networks"]},
                "put": {"operationId": "updatePolicy", "tags": ["networks"]},
            },
        },
    }
    spec_path = tmp_path / "spec.json"
    spec_path.write_text(json.dumps(spec), encoding="utf-8")
    catalog = ProviderCatalog(
        resources={
            "meraki_network_group_policy": frozenset(
                {"force_delete", "id", "network_id"}
            ),
        },
        source="fixture",
    )
    generator = HclImportGenerator(
        OpenApiParser(spec_path), AlertDispatcher([recorder]), lambda: catalog
    )
    graph = NetworkGraph(
        organization_id="org-123",
        networks=(),
        devices=(),
        features=(
            FeatureConfiguration(
                "/networks/{networkId}/groupPolicies/{groupPolicyId}",
                ("N_1", "101"),
            ),
        ),
    )
    report = generator.generate(graph, tmp_path)
    content = report.imports_file.read_text(encoding="utf-8")
    assert report.imports_written == 1
    assert "to = meraki_network_group_policy.n_1_101\n" in content
    assert 'id = "N_1,false,101"' in content


def test_unmatched_entity_is_flagged_as_provider_gap(
    spec_parser: OpenApiParser, tmp_path: Path, recorder: RecordingNotifier
) -> None:
    """A mutable entity the provider has no resource for must surface as
    an unsupported coverage gap, never as a guessed import."""
    stripped = {
        name: attrs
        for name, attrs in fixture_catalog().resources.items()
        if name != "meraki_sensor_relationships"
    }
    generator = HclImportGenerator(
        spec_parser,
        AlertDispatcher([recorder]),
        lambda: ProviderCatalog(resources=stripped, source="fixture"),
    )
    graph = NetworkGraph(
        organization_id="org-123",
        networks=(),
        devices=(),
        features=(
            FeatureConfiguration(
                "/networks/{networkId}/sensor/relationships", ("N_1",)
            ),
        ),
    )
    report = generator.generate(graph, tmp_path)
    assert report.imports_written == 0
    assert len(report.unsupported) == 1
    assert (
        "No CiscoDevNet/meraki provider resource matches"
        in report.unsupported[0].reason
    )
    assert recorder.events[0].event_type is EventType.UNSUPPORTED_FEATURE_FLAGGED
