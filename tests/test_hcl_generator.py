class RecordingNotifier(Notifier):
    channel = "recording"

    def __init__(self) -> None:
        self.events: list[AlertEvent] = []

    def send(self, event: AlertEvent) -> None:
        self.events.append(event)


@pytest.fixture()
def recorder() -> RecordingNotifier:
    return RecordingNotifier()


@pytest.fixture()
def generator(
    spec_parser: OpenApiParser, recorder: RecordingNotifier
) -> HclImportGenerator:
    return HclImportGenerator(
        spec_parser, AlertDispatcher([recorder]), fixture_catalog
    )


def _network(network_id: str = "N_1") -> MerakiNetwork:
    return MerakiNetwork.from_payload({"id": network_id, "organizationId": "org-123"})


def _graph(**overrides: tuple) -> NetworkGraph:  # type: ignore[type-arg]
    values = {
        "networks": (_network(),),
        "devices": (
            MerakiDevice.from_payload({"serial": "Q2AB-CDEF-GHIJ", "networkId": "N_1"}),
        ),
        "features": (
            FeatureConfiguration(
                "/networks/{networkId}/appliance/vlans/{vlanId}", ("N_1", "10")
            ),
        ),
    }
    values.update(overrides)
    return NetworkGraph(organization_id="org-123", **values)


def test_generates_import_blocks_for_all_mapped_assets(
    generator: HclImportGenerator, tmp_path: Path, recorder: RecordingNotifier
) -> None:
    report = generator.generate(_graph(), tmp_path)
    content = report.imports_file.read_text(encoding="utf-8")

    assert report.imports_written == 3
    assert report.unsupported == ()
    assert recorder.events == []
    assert "to = meraki_network.n_1\n" in content
    # meraki_network's identity demands the (always-known) org ID too.
    assert 'id = "org-123,N_1"' in content
    assert "to = meraki_device.q2ab_cdef_ghij\n" in content
    assert "to = meraki_appliance_vlan.n_1_10\n" in content
    assert 'id = "N_1,10"' in content
    assert content.startswith("# Generated by meraki2tf")


def test_unmapped_asset_triggers_exception_audit(
    generator: HclImportGenerator,
    tmp_path: Path,
    recorder: RecordingNotifier,
    caplog: pytest.LogCaptureFixture,
) -> None:
    graph = _graph(
        features=(
            FeatureConfiguration("/networks/{networkId}/unknownFeature", ("N_1",)),
        )
    )
    with caplog.at_level(logging.ERROR, logger="meraki2tf.hcl_generator"):
        report = generator.generate(graph, tmp_path)

    assert report.imports_written == 2  # network + device still written
    assert len(report.unsupported) == 1
    flagged = report.unsupported[0]
    assert flagged.api_path == "/networks/{networkId}/unknownFeature"
    assert "No Terraform resource maps" in flagged.reason
    assert any("UNSUPPORTED FEATURE" in record.message for record in caplog.records)

    assert len(recorder.events) == 1
    event = recorder.events[0]
    assert event.event_type is EventType.UNSUPPORTED_FEATURE_FLAGGED
    assert event.details["identifiers"] == ["N_1"]


